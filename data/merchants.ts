const m = (
  name: string,
  category: Category,
  aliases?: string[],
  note?: string,
): Merchant => ({ name, category, aliases, note });

/** A merchant that belongs to a brand some cards earn extra with. */
const b = (
  name: string,
  category: Category,
  brand: Brand,
  aliases?: string[],
  note?: string,
): Merchant => ({ ...m(name, category, aliases, note), brand });


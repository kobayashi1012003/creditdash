import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, parse } from "node:path";

/**
 * Lists the card art actually present in public/cards/, writes smaller copies
 * of each, and records both in a module the client can import.
 *
 * Without the list, CardFace would have to request /cards/<id>.webp and wait
 * for a 404 to know the file is missing, which paints a blank card for a
 * frame and puts a failed request on the wire for every card with no art.
 * Most cards have no art, so that is the normal case, not the edge case.
 *
 * The smaller copies exist because Next's image optimiser does nothing on
 * Cloudflare Workers without a Cloudflare Images binding: /_next/image returns the
 * original at every requested width. Measured under npm run preview, a
 * textured Amex face is 320 KB whether it is drawn at 160px or 600px. So the
 * widths are cut here, once, and CardFace's loader picks the smallest one
 * that is still sharp enough.
 *
 * Drop a file in public/cards/ and the next build picks it up and sizes it.
 * The copies go to public/cards/w/, which is gitignored and regenerated.
 */

const DIR = join(process.cwd(), "public", "cards");
const OUT = join(process.cwd(), "data", "card-art.generated.ts");
const EXTENSIONS = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);

/** Widths cut from every source wider than them. The original is the top. */
const WIDTHS = [480, 720, 960];

let files = [];
try {
  files = readdirSync(DIR);
} catch {
  mkdirSync(DIR, { recursive: true });
}

// sharp is a devDependency. If it is missing, the manifest still lists the
// originals and CardFace serves them full size: slower, never broken.
let sharp = null;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("card art: sharp not available, serving originals only");
}

const art = {};
for (const file of files) {
  const { name, ext } = parse(file);
  if (!EXTENSIONS.has(ext.toLowerCase())) continue;
  if (name.startsWith(".") || name.startsWith("_")) continue;
  // A card id wins its first match, so one id cannot have two formats fight.
  if (art[name]) continue;

  const source = join(DIR, file);
  const entry = { src: `/cards/${file}`, width: 0, variants: [] };

  if (sharp) {
    const { width = 0 } = await sharp(source).metadata();
    entry.width = width;
    const sourceTime = statSync(source).mtimeMs;
    for (const w of WIDTHS) {
      if (w >= width) continue; // never enlarge; the original covers it
      const dir = join(DIR, "w", String(w));
      const target = join(dir, `${name}.webp`);
      // Skip work that is already done, so dev and typecheck stay fast.
      if (!existsSync(target) || statSync(target).mtimeMs < sourceTime) {
        mkdirSync(dir, { recursive: true });
        await sharp(source).resize({ width: w }).webp({ quality: 80, effort: 5 }).toFile(target);
      }
      entry.variants.push(w);
    }
  }

  art[name] = entry;
}

const entries = Object.entries(art).sort(([a], [b]) => a.localeCompare(b));

writeFileSync(
  OUT,
  `// Generated by scripts/build-card-art-manifest.mjs. Do not edit.
// Lists the card art present in public/cards/ at build time, with the
// smaller widths cut into public/cards/w/<width>/<id>.webp.

export type CardArt = {
  /** The original file. */
  src: string;
  /** The original's width in pixels, 0 if it could not be read. */
  width: number;
  /** Widths available under /cards/w/, smallest first. */
  variants: number[];
};

export const CARD_ART: Record<string, CardArt> = {
${entries.map(([id, e]) => `  ${JSON.stringify(id)}: ${JSON.stringify(e)},`).join("\n")}
};
`,
);

console.log(
  `card art manifest: ${entries.length} ${entries.length === 1 ? "file" : "files"}`,
);

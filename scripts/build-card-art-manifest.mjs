import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, parse } from "node:path";

/**
 * Lists the card art actually present in public/cards/ and writes it to a
 * module the client can import.
 *
 * Without this, CardFace would have to request /cards/<id>.webp and wait for
 * a 404 to know the file is missing, which paints a blank card for a frame
 * and puts a failed request on the wire for every card with no art. Most
 * cards have no art, so that is the normal case, not the edge case.
 *
 * Drop a file in public/cards/ and the next build picks it up.
 */

const DIR = join(process.cwd(), "public", "cards");
const OUT = join(process.cwd(), "data", "card-art.generated.ts");
const EXTENSIONS = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);

let files = [];
try {
  files = readdirSync(DIR);
} catch {
  mkdirSync(DIR, { recursive: true });
}

const art = {};
for (const file of files) {
  const { name, ext } = parse(file);
  if (!EXTENSIONS.has(ext.toLowerCase())) continue;
  if (name.startsWith(".") || name.startsWith("_")) continue;
  // A card id wins its first match, so one id cannot have two formats fight.
  art[name] ??= `/cards/${file}`;
}

const entries = Object.entries(art).sort(([a], [b]) => a.localeCompare(b));

writeFileSync(
  OUT,
  `// Generated by scripts/build-card-art-manifest.mjs. Do not edit.
// Lists the card art present in public/cards/ at build time.

export const CARD_ART: Record<string, string> = {
${entries.map(([id, path]) => `  ${JSON.stringify(id)}: ${JSON.stringify(path)},`).join("\n")}
};
`,
);

console.log(
  `card art manifest: ${entries.length} ${entries.length === 1 ? "file" : "files"}`,
);
